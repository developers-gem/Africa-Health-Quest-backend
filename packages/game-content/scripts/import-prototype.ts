/**
 * One-off, reproducible import of the Lovable prototype content into the canonical format.
 * Text is copied verbatim; only structure is added (stable step/choice ids, ISO country codes, sort order).
 * Usage: npm run import:prototype -w @ahq/game-content
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { COUNTRIES, MISSIONS, TIERS } from "../../../legacy/lovable-prototype/game-data.ts";

const iso = (id: string) => id.toUpperCase();
const missions = MISSIONS.map((m, i) => ({
  key: m.id,
  countryCode: iso(m.country),
  tier: m.tier,
  icon: m.icon,
  sortOrder: i + 1,
  title: m.title,
  story: m.story,
  steps: m.steps.map((s, si) => ({
    stepId: `s${si + 1}`,
    prompt: s.prompt,
    choices: s.choices.map((c, ci) => ({
      choiceId: `s${si + 1}c${ci + 1}`,
      text: c.text,
      correct: c.correct,
      feedback: c.feedback,
    })),
  })),
}));
const countries = COUNTRIES.map((c, i) => ({
  code: iso(c.id),
  name: c.name,
  flagEmoji: c.flag,
  focus: c.focus,
  unlockHp: c.need,
  sortOrder: i + 1,
}));
const tierKeys = [
  "village_clinic",
  "community_hospital",
  "regional_medical_center",
  "national_health_system",
];
const tiers = TIERS.map((t, i) => ({
  index: i,
  key: tierKeys[i],
  name: t.name,
  icon: t.icon,
  hpRequired: t.need,
}));

const header = `// GENERATED by scripts/import-prototype.ts from legacy/lovable-prototype/game-data.ts — do not edit by hand.
// Contains clinical answer keys: backend and tooling only.
`;
const out = (name: string, type: string, value: unknown) =>
  `export const ${name}: ${type} = ${JSON.stringify(value, null, 2)};\n`;
const file = fileURLToPath(new URL("../src/prototype-content.ts", import.meta.url));
writeFileSync(
  file,
  header +
    `import type { CountryContent, MissionContent, TierContent } from "@ahq/shared-types";\n\n` +
    out("PROTOTYPE_MISSIONS", "MissionContent[]", missions) +
    "\n" +
    out("PROTOTYPE_COUNTRIES", "CountryContent[]", countries) +
    "\n" +
    out("PROTOTYPE_TIERS", "TierContent[]", tiers),
);
process.stdout.write(
  `Wrote ${missions.length} missions, ${countries.length} countries, ${tiers.length} tiers to ${file}\n`,
);
